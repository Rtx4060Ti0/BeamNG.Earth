local dir = (arg[0]:match('^(.*)[/\\]') or '.')
local T = dofile(dir .. '/testlib.lua')
local p = require('beamngEarth/placementwait')
local h = p.new(false)
T.check(h.pausedByUs, 'running physics paused by placement')
for i=1,1200 do T.check(p.step(h,false,true)==nil,'terrain alone must not release a bridge spawn') end
T.check(p.step(h,true,true)==nil,'first collision frame')
T.check(p.step(h,true,true)==nil,'second collision frame')
T.check(p.step(h,true,true)=='place','three stable collision frames')
h=p.new(false)
T.check(p.step(h,false,false)=='cancel','manual resume cancels the wait')
h=p.new(true)
T.check(not h.pausedByUs,'preserve an existing player pause')
p.step(h,true,true);p.step(h,true,true)
T.check(p.step(h,true,true)=='place' and not h.pausedByUs,'placement may not resume a player pause')
T.done('placement wait')
